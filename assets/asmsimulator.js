                        self.carry = (valueToShift & (1 << (shiftAmount - 1))) !== 0;

                        // Führe die Shift-Right-Operation durch
                        self.gpr[regTo] = checkOperation(valueToShift >>> shiftAmount, true);
                        self.ip++;
                        break;

